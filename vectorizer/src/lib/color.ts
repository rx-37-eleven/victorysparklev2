// Piece preview coloring: golden-ratio hue stepping at fixed moderate
// saturation/lightness, so adjacent pieces contrast and the whole thing
// stays readable regardless of piece count.

const GOLDEN_RATIO_CONJUGATE = 0.6180339887498949;

export function pieceColor(index: number, saturation = 0.55, lightness = 0.55): [number, number, number] {
  const hue = (index * GOLDEN_RATIO_CONJUGATE) % 1;
  return hslToRgb(hue, saturation, lightness);
}

function hslToRgb(h: number, s: number, l: number): [number, number, number] {
  if (s === 0) {
    const v = Math.round(l * 255);
    return [v, v, v];
  }
  const q = l < 0.5 ? l * (1 + s) : l + s - l * s;
  const p = 2 * l - q;
  const r = hueToRgb(p, q, h + 1 / 3);
  const g = hueToRgb(p, q, h);
  const b = hueToRgb(p, q, h - 1 / 3);
  return [Math.round(r * 255), Math.round(g * 255), Math.round(b * 255)];
}

function hueToRgb(p: number, q: number, t: number): number {
  let tt = t;
  if (tt < 0) tt += 1;
  if (tt > 1) tt -= 1;
  if (tt < 1 / 6) return p + (q - p) * 6 * tt;
  if (tt < 1 / 2) return q;
  if (tt < 2 / 3) return p + (q - p) * (2 / 3 - tt) * 6;
  return p;
}
